// The token radar's model: one sealed snapshot of the protocol universe in, one ranked board out.
//
// Who is ranked. The board covers every slug on the snapshot's watchlist (the floor, never the
// ceiling) and adds every rankable pre-token protocol below the floor: the early rows the radar
// exists to find. A protocol is rankable when the snapshot records no token for it (no market cap,
// no CoinGecko id, no symbol) and it is not a wrapped, staked or bridged product of another
// protocol, not an exchange, and not a versioned pool. Above the floor the board ranks exactly the
// watchlist: a protocol the house's rule left out up there is a product of another protocol (its
// parentProtocol, a field the snapshot does not carry) and is not ranked as a launch of its own.
//
// Implied value follows only from the snapshot's own figures, and the base multiple is calibrated
// from the snapshot itself instead of picked by hand:
//
//   multiple   = median market-cap / TVL across the snapshot's live-token protocols,
//                clamped to [0.05, 0.50] so one outlier cannot set it
//   base       = tvl_usd x multiple
//   growthMult = 1 + clamp(change_7d, -60, 120) / 100 x 0.5
//   maturity   = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age unknown: 365 days)
//   implied    = max(1, round(base x growthMult x maturity))
//
// The dashboard states the calibrated multiple, how many live protocols set it, and the formula, and
// its page recomputes every row from the same figures. No protocol name is ever special-cased: the
// same function scores every row, and the live-token protocols are kept apart with the market's own
// values, never mixed into the ranked board.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants, as the dashboard states them. */
export interface ModelConstants {
  /** Calibrated from the snapshot's live-token protocols; see calibrateMultiple. */
  base_multiple: number;
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
  /** Clamp on the calibrated multiple, so outliers cannot set it. */
  multiple_floor: number;
  multiple_cap: number;
}

/** The fixed part of the model; base_multiple is filled in by calibration. */
export const MODEL_SHAPE: Omit<ModelConstants, 'base_multiple'> = {
  growth_weight: 0.5,
  growth_floor: -60,
  growth_cap: 120,
  maturity_floor: 0.6,
  maturity_range: 0.4,
  maturity_days: 1095,
  unknown_age_days: 365,
  multiple_floor: 0.05,
  multiple_cap: 0.5,
};

/** The model's version label: the dashboard names it. */
export const MODEL_VERSION = 'radar-2';

