const DAY_MS = 86_400_000;
const round4 = (n: number): number => Math.round(n * 1e4) / 1e4;

/** A finite number, else `fallback`. */
function finite(value: unknown, fallback: number): number {
  return typeof value === 'number' && Number.isFinite(value) ? value : fallback;
}

/** A whole day count from `from` to `to`, clamped at zero; null when either date is absent or bad. */
export function ageDays(asOf: string, listedAt: string | null): number | null {
  if (listedAt === null) return null;
  const a = Date.parse(`${asOf}T00:00:00Z`);
  const b = Date.parse(`${listedAt}T00:00:00Z`);
  if (!Number.isFinite(a) || !Number.isFinite(b)) return null;
  return Math.max(0, Math.floor((a - b) / DAY_MS));
}

/** The median of a sorted array, or null when it holds nothing. */
export function median(sorted: number[]): number | null {
  if (sorted.length === 0) return null;
  const mid = Math.floor(sorted.length / 2);
  if (sorted.length % 2 === 1) return sorted[mid]!;
  return (sorted[mid - 1]! + sorted[mid]!) / 2;
}

/**
 * The base multiple, calibrated from the snapshot: the median market-cap-to-TVL ratio across the
 * live-token protocols that carry both figures, exchanges left out, clamped so that a thin or
 * skewed live set cannot set an extreme multiple. Falls back to 0.25 when the snapshot carries no
 * usable live protocol.
 */
export function calibrateMultiple(protocols: SnapshotProtocol[]): Calibration {
  const ratios = protocols
    .filter((p) => p.mcap_usd !== null && p.mcap_usd > 0 && p.tvl_usd > 0 && p.category !== 'CEX')
    .map((p) => p.mcap_usd! / p.tvl_usd)
    .sort((a, b) => a - b);
  const raw = median(ratios);
  if (raw === null || !Number.isFinite(raw)) {
    return { multiple: 0.25, median_ratio: 0.25, live_count: 0, clamped: false };
  }
  const clamped = Math.min(MODEL_SHAPE.multiple_cap, Math.max(MODEL_SHAPE.multiple_floor, raw));
  return {
    multiple: round4(clamped),
    median_ratio: round4(raw),
    live_count: ratios.length,
    clamped: clamped !== raw,
  };
}

/** The multipliers and the implied value one protocol gets under `model`. */
export function impliedValue(
  protocol: SnapshotProtocol,
  asOf: string,
  model: ModelConstants,
): { implied: number; growthPct: number; growthMult: number; maturityMult: number; age: number | null } {
  const age = ageDays(asOf, protocol.listed_at);
  const rawGrowth = finite(protocol.change_7d, 0);
  const growthPct = Math.min(model.growth_cap, Math.max(model.growth_floor, rawGrowth));
  const growthMult = 1 + (growthPct / 100) * model.growth_weight;
  const ageForModel = age ?? model.unknown_age_days;
  const maturityMult =
    model.maturity_floor + (Math.min(Math.max(ageForModel, 0), model.maturity_days) / model.maturity_days) * model.maturity_range;
  const base = protocol.tvl_usd * model.base_multiple;
  const implied = Math.max(1, Math.round(base * growthMult * maturityMult));
  return { implied, growthPct, growthMult, maturityMult, age };
}

/** DefiLlama's version-marker rule: a name ending in a release is a pool of another protocol. */
const VERSIONED = /\s(V\d+(\.\d+)?|v\d+(\.\d+)?|\d+\.\d+)$/;

/** Categories that are products of another protocol's token, never a launch of their own. */
const PRODUCT_CATEGORIES = new Set(['Bridge', 'Canonical Bridge', 'Liquid Staking', 'Liquid Restaking', 'Restaked BTC', 'CEX']);

/** Exchanges, whose named products are exchange products, not launches. */
const EXCHANGE_PREFIX = /^(Binance|Coinbase|Bybit|Kraken|Bitget|OKX|Bitfinex|Gemini)\b/;

/** A wrapped, staked or staking product of a token that already trades. */
const WRAPPED_WORD = /\b(wrapped|staked|staking)\b/i;

/** Whether a protocol records no token at all. */
export function isPreToken(p: SnapshotProtocol): boolean {
  return p.mcap_usd === null && p.gecko_id === null && p.symbol === null;
}

/** Whether a protocol is one the board may rank: pre-token and a launch of its own. */
export function isRankable(p: SnapshotProtocol): boolean {
  return (
    isPreToken(p) &&
    !PRODUCT_CATEGORIES.has(p.category ?? '') &&
    !VERSIONED.test(p.name) &&
    !WRAPPED_WORD.test(p.name) &&
    !EXCHANGE_PREFIX.test(p.name)
  );
}

/** The protocols the board ranks, strongest first, with ranks 1..n. */
export function buildBoard(snapshot: Snapshot, model: ModelConstants): BoardRow[] {
  const index = new Map(snapshot.protocols.map((p) => [p.slug, p]));
  const chosen = new Map<string, SnapshotProtocol>();
  // The watchlist is the floor: every slug it names, whatever else the snapshot says.
  for (const slug of snapshot.watchlist) {
    const p = index.get(slug);
    if (p !== undefined) chosen.set(slug, p);
  }
  // The early radar: every rankable pre-token protocol below the watchlist floor. Above the floor
  // the board ranks exactly the watchlist: a protocol the house's rule left out up there is a
  // product of another protocol, and the snapshot's ten fields cannot tell the board otherwise.
  for (const p of snapshot.protocols) {
    if (!chosen.has(p.slug) && isRankable(p) && p.tvl_usd < snapshot.floor_usd) chosen.set(p.slug, p);
  }

  const scored = [...chosen.values()].map((p) => {
    const { implied, growthPct, growthMult, maturityMult, age } = impliedValue(p, snapshot.as_of, model);
    return { p, implied, growthPct, growthMult, maturityMult, age };
  });
  scored.sort((a, b) => b.implied - a.implied || (a.p.slug < b.p.slug ? -1 : a.p.slug > b.p.slug ? 1 : 0));
  const watchlist = new Set(snapshot.watchlist);
  return scored.map((s, i) => ({
    rank: i + 1,
    slug: s.p.slug,
    name: s.p.name,
    category: s.p.category,
    chains: s.p.chains,
    tvl_usd: s.p.tvl_usd,
    change_7d: s.p.change_7d,
    mcap_usd: s.p.mcap_usd,
    listed_at: s.p.listed_at,
    gecko_id: s.p.gecko_id,
    symbol: s.p.symbol,
    token_status: 'pre-token',
    on_watchlist: watchlist.has(s.p.slug),
    age_days: s.age,
    implied_value_usd: s.implied,
    model: {
      base_multiple: model.base_multiple,
      growth_pct: s.growthPct,
      growth_multiplier: round4(s.growthMult),
      maturity_multiplier: round4(s.maturityMult),
      age_days: s.age,
    },
    farm: farmTotals(s.p, s.age),
    farm_steps: farmSteps(s.p, s.age).map(stepText),
  }));
}

/** A step as one string: its action, then its cost and time, within the gate's 20..600 characters. */
export function stepText(step: FarmStep): string {
  let s = `${step.text} Cost: ${step.cost}. Time: ${step.time}.`;
  if (s.length > 600) s = `${s.slice(0, 596)}...`;
  if (s.length < 20) s = `${s} Hold the position and check the protocol's own page.`;
  return s;
}

/** The first chain a protocol names, or a neutral phrase. */
function chainOf(p: SnapshotProtocol): string {
  return p.chains.length > 0 ? p.chains[0]! : 'its main chain';
}

/**
 * One transaction's gas on a chain, in dollars: an estimate from the chain's family, not a quote.
 * Ethereum mainnet is the expensive case; fast chains cost cents; rollups and cheap chains sit
 * between; anything the table does not name takes the middle estimate.
 */
export function gasPerTx(chain: string): number {
  const c = chain.toLowerCase();
  if (c === 'ethereum') return 9;
  if (/(solana|sui|aptos|near|sei|movement|eclipse|fuel)/.test(c)) return 0.05;
  if (/(arbitrum|optimism|base|linea|blast|mode|scroll|zksync|starknet|unichain|ink|soneium|world chain|zircuit|manta|mantle|metis|fraxtal|katana|swellchain|tac|rise|tempo|op_bnb|x layer|polygon zkevm|lisk|morph|sophon|abstract|bob|berachain|monad|megaeth|pharos|hemi)/.test(c)) return 0.5;
  if (/(binance|polygon|avalanche|tron|fantom|cronos|kava|klaytn|celo|moonbeam|evmos|telos|pulse|thundercore|ronin|saga|flow|flare|core|bifrost|astar)/.test(c)) return 0.3;
  return 2;
}

/** A dollar amount as the farm plan writes it: cents below a dollar, whole dollars above it. */
export function fmtMoney(n: number): string {
  if (n < 1) return `$${n.toFixed(2)}`;
  return `$${Math.round(n)}`;
}

/** How much capital one farm position needs, from the protocol's own TVL. */
export function capitalFor(p: SnapshotProtocol): number {
  if (p.tvl_usd >= 5_000_000_000) return 250;
  if (p.tvl_usd >= 1_000_000_000) return 150;
  if (p.tvl_usd >= 100_000_000) return 100;
  return 50;
}

/** How long to hold, from the protocol's age: younger protocols get a longer qualifying window. */
export function holdDaysFor(age: number | null): number {
  if (age === null) return 30;
  if (age < 180) return 60;
  if (age < 365) return 45;
  return 30;
}

/** The category's one action, in the words a farmer can follow. */
export function actionFor(p: SnapshotProtocol, capital: number, chain: string): string {
  const c = (p.category ?? '').toLowerCase();
  const name = p.name;
  if (c.includes('curator')) return `Allocate $${capital} to a ${name} curator vault on ${chain} and keep the vault shares.`;
  if (c.includes('dex')) return `Provide $${capital} of liquidity to ${name}'s main pool on ${chain} and keep the position in range.`;
  if (c.includes('allocator')) return `Deposit $${capital} into a ${name} allocation vault on ${chain} and keep the shares.`;
  if (c.includes('rwa')) return `Mint $${capital} of the protocol's yield-bearing asset through ${name} on ${chain} and hold it.`;
  if (c.includes('lend') || c.includes('collateral')) return `Supply $${capital} of USDC to ${name} on ${chain} and keep the supply position open.`;
  if (c.includes('leveraged')) return `Open a $${capital} leveraged position on ${name}'s main market on ${chain} with modest leverage and keep it open.`;
  if (c.includes('yield')) return `Deposit $${capital} into ${name}'s highest-TVL strategy vault on ${chain} and keep the shares.`;
  if (c.includes('derivative') || c.includes('perpetual') || c.includes('basis') || c.includes('interest rate')) return `Deposit $${capital} of USDC as margin on ${name} on ${chain} and open one small hedged position.`;
  if (c.includes('cdp')) return `Lock $${capital} of collateral in a ${name} vault on ${chain} and mint a small amount of its stable asset.`;
  if (c.includes('bridge')) return `Bridge $${capital} of USDC to ${chain} through ${name} and use the bridged funds in its app.`;
  if (c.includes('chain')) return `Bridge $${capital} to ${name}'s chain and use its native app: one swap and one stake.`;
  if (c.includes('restak') || c.includes('staking')) return `Stake $${capital} of the chain's staking asset through ${name} and keep the receipt token.`;
  if (c.includes('liquidity manager')) return `Deposit $${capital} into a ${name} managed liquidity position on ${chain} and keep it open.`;
  if (c.includes('btc') || c.includes('anchor')) return `Deposit $${capital} of wrapped BTC into ${name} on ${chain} and keep the receipt.`;
  if (c.includes('cedefi')) return `Deposit $${capital} into a ${name} CeDeFi vault on ${chain} and keep the shares.`;
  if (c.includes('stablecoin')) return `Mint or hold $${capital} of the stable asset through ${name} on ${chain}.`;
  if (c.includes('farm')) return `Deposit $${capital} into ${name}'s main farm on ${chain} and keep the position staked.`;
  if (c.includes('prediction')) return `Fund $${capital} and place one market position on ${name}.`;
  if (c.includes('insurance')) return `Buy $${capital} of cover from ${name} on ${chain} and keep the policy.`;
  if (c.includes('payment')) return `Route $${capital} of payments through ${name} on ${chain} and keep the receipts.`;
  if (c.includes('governance')) return `Lock $${capital} in ${name}'s governance vault on ${chain} and vote once.`;
  if (c.includes('card')) return `Load $${capital} onto the ${name} card and spend it once.`;
  if (c.includes('index')) return `Buy $${capital} of the ${name} index token on ${chain} and hold it.`;
  if (c.includes('otc')) return `Place one $${capital} order through ${name} and settle it on ${chain}.`;
  return `Deposit $${capital} of USDC into ${name} on ${chain} and keep the position open.`;
}

/**
 * A protocol's farm plan: seven steps, each an action with a cost and a time. The plan is derived
 * from the protocol's own record (category, chains, TVL, age), never from a hand-written list of
 * names. Gas follows the chain's family; capital follows TVL; the hold follows age.
 */
export function farmSteps(p: SnapshotProtocol, age: number | null): FarmStep[] {
  const chain = chainOf(p);
  const capital = capitalFor(p);
  const hold = holdDaysFor(age);
  const gas = gasPerTx(chain);
  const g = fmtMoney(gas);
  return [
    {
      text: `Open a fresh wallet that holds only the funds you plan to farm, and write its seed phrase on paper kept offline.`,
      cost: `about ${g} of gas for the first transaction on ${chain}`,
      time: '5 minutes',
    },
    {
      text: actionFor(p, capital, chain),
      cost: `$${capital} of capital and about ${g} of gas`,
      time: '15 minutes to set up',
    },
    {
      text: `Use a second feature of the protocol within the first week: a swap, a borrow, a stake or a vote, so the wallet shows more than one kind of activity.`,
      cost: `about ${g} of gas`,
      time: '10 minutes',
    },
    {
      text: `Make one qualifying action each week, such as a deposit, a borrow, a swap or a vote, and keep the position above the minimum size.`,
      cost: `about ${g} of gas a week`,
      time: '10 minutes a week',
    },
    {
      text: `Hold the position for at least ${hold} days so the activity lands in more than one snapshot window.`,
      cost: `the $${capital} stays in the position`,
      time: `${hold} days`,
    },
    {
      text: `Before you withdraw, open the protocol's own points or rewards page from its official site and claim only from the link it publishes; never pay anyone to claim.`,
      cost: 'no fee to check',
      time: '10 minutes',
    },
    {
      text: `Unwind in two or three withdrawals a few days apart, and keep the farm log: wallet, dates, amounts and every transaction hash.`,
      cost: `about ${fmtMoney(gas * 2)} of gas to exit`,
      time: '15 minutes',
    },
  ];
}

/** The plan's totals: capital at work, estimated gas across the plan, hold, and active minutes. */
export function farmTotals(p: SnapshotProtocol, age: number | null): BoardRow['farm'] {
  const capital = capitalFor(p);
  const hold = holdDaysFor(age);
  const gas = gasPerTx(chainOf(p));
  const weeks = Math.ceil(hold / 7);
  const transactions = 4 + weeks + 2;
  return {
    capital_usd: capital,
    gas_per_tx_usd: gas,
    est_gas_usd: Math.round(gas * transactions * 100) / 100,
    hold_days: hold,
    active_minutes: 5 + 15 + 10 + 10 * weeks + 10 + 15,
  };
}

/** The live-token protocols, by market cap, for the dashboard's Live token view. */
export function liveRows(snapshot: Snapshot): LiveRow[] {
  return snapshot.protocols
    .filter((p) => !isPreToken(p) && p.category !== 'CEX')
    .sort((a, b) => (b.mcap_usd ?? 0) - (a.mcap_usd ?? 0) || b.tvl_usd - a.tvl_usd)
    .slice(0, LIVE_ROWS)
    .map((p) => ({
      slug: p.slug,
      name: p.name,
      category: p.category,
      chains: p.chains,
      tvl_usd: p.tvl_usd,
      mcap_usd: p.mcap_usd,
      change_7d: p.change_7d,
      mcap_tvl_ratio: p.mcap_usd !== null && p.tvl_usd > 0 ? round4(p.mcap_usd / p.tvl_usd) : null,
    }));
}

/** A board row's compact form for data.js, with the farm plan generated in the page. */
